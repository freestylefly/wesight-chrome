import { parseWeiboAccount, probeAccount } from "~lib/accounts"

const json = (value: unknown, status = 200) => new Response(JSON.stringify(value), { status })
const query = vi.fn()
const executeScript = vi.fn()
const createTab = vi.fn()
const getTab = vi.fn()
const removeTab = vi.fn()

beforeEach(() => {
  query.mockReset().mockResolvedValue([])
  executeScript.mockReset()
  createTab.mockReset().mockResolvedValue({ id: 100, url: "https://web.okjike.com/", status: "loading", active: false })
  getTab.mockReset().mockImplementation(async (id: number) => ({ id, url: "https://web.okjike.com/", status: "complete", active: false }))
  removeTab.mockReset().mockResolvedValue(undefined)
  vi.stubGlobal("chrome", { tabs: { query, create: createTab, get: getTab, remove: removeTab }, scripting: { executeScript } })
  vi.stubGlobal("fetch", vi.fn(async () => json({})))
})
afterEach(() => { vi.unstubAllGlobals(); vi.useRealTimers() })

describe("browser account probes", () => {
  test("reads an already open CSDN page without requiring an extension receiver or another tab", async () => {
    query.mockResolvedValue([{ id: 1 }])
    executeScript.mockResolvedValue([{ result: { state: "logged_in", name: "创作者" } }])
    expect(await probeAccount("csdn")).toMatchObject({ state: "logged_in", name: "创作者" })
    expect(executeScript).toHaveBeenCalledWith(expect.objectContaining({ target: { tabId: 1 }, args: ["csdn"], func: expect.any(Function) }))
    expect(fetch).not.toHaveBeenCalled()
  })
  test("does not let an inconclusive tab hide a logged-in Weibo home tab", async () => {
    query.mockResolvedValue([{ id: 1 }, { id: 2 }, { id: 3, discarded: true }])
    executeScript.mockImplementation(async ({ target }) => [{ result: target.tabId === 1 ? { state: "unknown" } : { state: "logged_in", name: "微博用户" } }])
    expect(await probeAccount("weibo-article")).toMatchObject({ state: "logged_in", name: "微博用户" })
    expect(executeScript).toHaveBeenCalledTimes(2)
    expect(fetch).not.toHaveBeenCalled()
  })
  test("uses the current CSDN toolbar endpoint without an open page", async () => {
    vi.mocked(fetch).mockResolvedValue(json({ code: 200, data: { nickName: "苍何", avatar: "https://example.com/avatar.png" } }))
    expect(await probeAccount("csdn")).toMatchObject({ state: "logged_in", name: "苍何" })
    expect(fetch).toHaveBeenCalledWith("https://g-api.csdn.net/community/toolbar-api/v1/get-user-info", expect.objectContaining({ credentials: "include", cache: "no-store" }))
  })
  test("prefers an authenticated X tab to a stale login tab, while recognizing a definite logout", async () => {
    query.mockResolvedValue([{ id: 1 }, { id: 2 }])
    getTab.mockImplementation(async id => ({ id, url: id === 1 ? "https://x.com/i/flow/login" : "https://x.com/home", status: "complete" }))
    executeScript.mockImplementation(async ({ target }) => [{ result: target.tabId === 1 ? { state: "login_required" } : { state: "logged_in", name: "creator" } }])
    expect(await probeAccount("x-article")).toMatchObject({ state: "logged_in", name: "creator" })
    query.mockResolvedValue([{ id: 1 }])
    expect(await probeAccount("x-article")).toMatchObject({ state: "login_required" })
  })
  test("shares the same read-only probe for X article and dynamic account requests", async () => {
    query.mockResolvedValue([{ id: 8 }])
    getTab.mockResolvedValue({ id: 8, url: "https://x.com/home", status: "complete" })
    executeScript.mockResolvedValue([{ result: { state: "logged_in", name: "same_account" } }])
    const article = probeAccount("x-article")
    const dynamic = probeAccount("x-post")
    expect(dynamic).toBe(article)
    expect(await dynamic).toMatchObject({ state: "logged_in", name: "same_account" })
    expect(executeScript).toHaveBeenCalledTimes(1)
    expect(executeScript).toHaveBeenCalledWith(expect.objectContaining({ args: ["x-article"] }))
    expect(fetch).not.toHaveBeenCalled()
  })
  test("falls back to the account endpoint when a tab was closed or script execution is unavailable", async () => {
    query.mockResolvedValue([{ id: 4 }])
    executeScript.mockRejectedValue(new Error("Tab closed"))
    vi.mocked(fetch).mockResolvedValue(json({ code: 200, data: { userName: "creator" } }))
    expect(await probeAccount("csdn")).toMatchObject({ state: "logged_in", name: "creator" })
  })
  test("bounds an unresponsive tab check before using the endpoint", async () => {
    vi.useFakeTimers()
    query.mockResolvedValue([{ id: 4 }])
    executeScript.mockImplementation(() => new Promise(() => {}))
    vi.mocked(fetch).mockResolvedValue(json({ code: 200, data: { nickName: "creator" } }))
    const result = probeAccount("csdn")
    await vi.advanceTimersByTimeAsync(2001)
    expect(await result).toMatchObject({ state: "logged_in" })
  })
  test("distinguishes a definite expired session from a network or schema failure", async () => {
    vi.mocked(fetch).mockResolvedValueOnce(json({ code: 401 }, 401))
    expect(await probeAccount("csdn")).toMatchObject({ state: "login_required" })
    vi.mocked(fetch).mockRejectedValueOnce(new TypeError("Failed to fetch"))
    expect(await probeAccount("csdn")).toMatchObject({ state: "unknown" })
    vi.mocked(fetch).mockResolvedValueOnce(json({ code: 200, data: { changed: true } }))
    expect(await probeAccount("csdn")).toMatchObject({ state: "unknown" })
  })
  test("recognizes the current Weibo bootstrap even when the page includes login scripts", async () => {
    vi.mocked(fetch).mockResolvedValue(new Response('<script>window.$CONFIG={"user":{"idstr":"123456","screen_name":"微博用户"}};</script><script src="https://passport.weibo.com/login.js"></script>'))
    expect(await probeAccount("weibo-article")).toMatchObject({ state: "logged_in", name: "微博用户" })
  })
  test("only treats a real Weibo login redirect as a confirmed logged-out state", async () => {
    vi.mocked(fetch).mockResolvedValueOnce(new Response('<script src="https://passport.weibo.com/login.js"></script>'))
    expect(await probeAccount("weibo-article")).toMatchObject({ state: "unknown" })
    const response = new Response("登录")
    Object.defineProperty(response, "url", { value: "https://passport.weibo.com/sso/signin" })
    vi.mocked(fetch).mockResolvedValueOnce(response)
    expect(await probeAccount("weibo-article")).toMatchObject({ state: "login_required" })
  })
  test("shares simultaneous checks for the same platform", async () => {
    vi.mocked(fetch).mockResolvedValue(json({ code: 200, data: { nickName: "creator" } }))
    const [first, second] = await Promise.all([probeAccount("csdn"), probeAccount("csdn")])
    expect(first).toEqual(second)
    expect(fetch).toHaveBeenCalledTimes(1)
  })
  test.each(["xiaohongshu", "jike-post"] as const)("reads an existing %s tab without a content-script receiver", async platformId => {
    query.mockResolvedValue([{ id: 8 }])
    executeScript.mockResolvedValue([{ result: { state: "logged_in", name: "已登录本人", avatar: "https://example.com/self.jpg" } }])
    const result = await probeAccount(platformId)
    expect(result).toMatchObject({ state: "logged_in", name: "已登录本人", avatar: "https://example.com/self.jpg", checkedAt: expect.any(String) })
    expect(executeScript).toHaveBeenCalledWith(expect.objectContaining({ target: { tabId: 8 }, args: [platformId] }))
    expect(fetch).not.toHaveBeenCalled()
  })
  test.each(["xiaohongshu", "jike-post"] as const)("timestamps and shares pending %s checks, then allows a new check after login", async platformId => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date("2026-10-15T12:00:00.000Z"))
    query.mockResolvedValue([{ id: 9 }])
    executeScript.mockResolvedValueOnce([{ result: { state: "login_required" } }])
    const first = probeAccount(platformId)
    const second = probeAccount(platformId)
    expect(first).toBe(second)
    expect(await first).toEqual({ state: "login_required", checkedAt: "2026-10-15T12:00:00.000Z" })
    expect(query).toHaveBeenCalledTimes(1)
    vi.setSystemTime(new Date("2026-10-15T12:00:02.000Z"))
    executeScript.mockResolvedValueOnce([{ result: { state: "logged_in", name: "新登录" } }])
    expect(await probeAccount(platformId)).toEqual({ state: "logged_in", name: "新登录", checkedAt: "2026-10-15T12:00:02.000Z" })
    expect(query).toHaveBeenCalledTimes(2)
  })
  test.each(["xiaohongshu", "jike-post"] as const)("bounds a stalled %s probe and does not assume an empty shell is authenticated", async platformId => {
    vi.useFakeTimers()
    const url = platformId === "xiaohongshu" ? "https://creator.xiaohongshu.com/new/home" : "https://web.okjike.com/"
    query.mockResolvedValue([{ id: 10, url, status: "complete" }])
    getTab.mockResolvedValue({ id: 10, url, status: "complete" })
    executeScript.mockImplementationOnce(() => new Promise(() => {}))
    const stalled = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(2001)
    expect(await stalled).toEqual({ state: "unknown", checkedAt: expect.any(String) })
    executeScript.mockResolvedValue([{ result: { state: "unknown" } }])
    const emptyShell = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(8001)
    expect(await emptyShell).toMatchObject({ state: "unknown", checkedAt: expect.any(String) })
    expect(fetch).not.toHaveBeenCalled()
  })
  test("records a failed dynamic tab query without rejecting the platform refresh", async () => {
    query.mockRejectedValueOnce(new Error("Browser query unavailable"))
    expect(await probeAccount("jike-post")).toMatchObject({ state: "unknown", checkedAt: expect.any(String) })
  })
  test("shares Weibo article and dynamic session probes", async () => {
    query.mockResolvedValue([{ id: 11 }])
    executeScript.mockResolvedValue([{ result: { state: "logged_in", name: "同一微博账号" } }])
    const [article, dynamic] = await Promise.all([probeAccount("weibo-article"), probeAccount("weibo-post")])
    expect(dynamic).toEqual(article)
    expect(executeScript).toHaveBeenCalledTimes(1)
  })
  test("does not create background pages for platforms with endpoint-based probes", async () => {
    expect(await probeAccount("weibo-post")).toMatchObject({ state: "unknown" })
    expect(createTab).not.toHaveBeenCalled()
  })
})

describe.each([
  { platformId: "jike-post" as const, homeUrl: "https://web.okjike.com/" },
  { platformId: "xiaohongshu" as const, homeUrl: "https://creator.xiaohongshu.com/new/home" },
  { platformId: "x-article" as const, homeUrl: "https://x.com/home" }
])("$platformId session detection without an open page", ({ platformId, homeUrl }) => {
  beforeEach(() => {
    createTab.mockResolvedValue({ id: 100, url: homeUrl, status: "loading", active: false })
    getTab.mockImplementation(async (id: number) => ({ id, url: homeUrl, status: "complete", active: false }))
  })
  test("uses the signed-in browser session in one temporary background page and cleans it up", async () => {
    executeScript.mockResolvedValue([{ result: { state: "logged_in", name: "已登录本人" } }])
    const first = probeAccount(platformId)
    expect(probeAccount(platformId)).toBe(first)
    if (platformId === "x-article") expect(probeAccount("x-post")).toBe(first)
    expect(await first).toMatchObject({ state: "logged_in", name: "已登录本人" })
    expect(createTab).toHaveBeenCalledTimes(1)
    expect(createTab).toHaveBeenCalledWith({ url: homeUrl, active: false })
    expect(query).toHaveBeenCalledWith({ url: platformId === "x-article" ? ["https://x.com/*", "https://twitter.com/*"] : [new URL(homeUrl).origin + "/*"] })
    expect(executeScript).toHaveBeenCalledTimes(1)
    expect(executeScript).toHaveBeenCalledWith(expect.objectContaining({ target: { tabId: 100 }, args: [platformId] }))
    expect(removeTab).toHaveBeenCalledTimes(1)
    expect(removeTab).toHaveBeenCalledWith(100)
    expect(fetch).not.toHaveBeenCalled()
  })
  test("ignores discarded pages and does not inject into or close them", async () => {
    query.mockResolvedValue([{ id: 8, discarded: true }])
    executeScript.mockResolvedValue([{ result: { state: "logged_in" } }])
    expect(await probeAccount(platformId)).toMatchObject({ state: "logged_in" })
    expect(executeScript).toHaveBeenCalledTimes(1)
    expect(executeScript).toHaveBeenCalledWith(expect.objectContaining({ target: { tabId: 100 } }))
    expect(removeTab).toHaveBeenCalledTimes(1)
    expect(removeTab).toHaveBeenCalledWith(100)
  })
  test("reuses an existing signed-in page without creating, navigating or removing a tab", async () => {
    query.mockResolvedValue([{ id: 8, url: new URL("/following", homeUrl).href, status: "complete", active: true }])
    executeScript.mockResolvedValue([{ result: { state: "logged_in", name: "本人" } }])
    expect(await probeAccount(platformId)).toMatchObject({ state: "logged_in", name: "本人" })
    expect(createTab).not.toHaveBeenCalled()
    expect(removeTab).not.toHaveBeenCalled()
    if (platformId === "x-article") expect(getTab).toHaveBeenCalledTimes(1)
    else expect(getTab).not.toHaveBeenCalled()
  })
  test("waits for an existing SPA to hydrate in the same tab", async () => {
    vi.useFakeTimers()
    query.mockResolvedValue([{ id: 8, url: homeUrl, status: "complete" }])
    executeScript.mockResolvedValueOnce([{ result: { state: "unknown" } }])
      .mockResolvedValueOnce([{ result: { state: "logged_in", name: "延迟加载" } }])
    const result = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(301)
    expect(await result).toMatchObject({ state: "logged_in", name: "延迟加载" })
    expect(executeScript).toHaveBeenCalledTimes(2)
    expect(createTab).not.toHaveBeenCalled()
    expect(removeTab).not.toHaveBeenCalled()
  })
  test("waits through initial navigation and a blank SPA shell before detecting the account", async () => {
    vi.useFakeTimers()
    getTab.mockResolvedValueOnce({ id: 100, url: "about:blank", pendingUrl: homeUrl, status: "loading", active: false })
    executeScript.mockResolvedValueOnce([{ result: { state: "unknown" } }])
      .mockResolvedValueOnce([{ result: { state: "logged_in" } }])
    const result = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(601)
    expect(await result).toMatchObject({ state: "logged_in" })
    expect(executeScript).toHaveBeenCalledTimes(2)
    expect(removeTab).toHaveBeenCalledTimes(1)
    expect(removeTab).toHaveBeenCalledWith(100)
  })
  test("does not accept an in-flight login shell before the signed-in session appears", async () => {
    vi.useFakeTimers()
    getTab.mockResolvedValueOnce({ id: 100, url: new URL("/login", homeUrl).href, status: "loading", active: false })
    executeScript.mockResolvedValueOnce([{ result: { state: "login_required" } }])
      .mockResolvedValueOnce([{ result: { state: "logged_in", name: "已登录" } }])
    const result = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(301)
    expect(await result).toMatchObject({ state: "logged_in", name: "已登录" })
    expect(removeTab).toHaveBeenCalledTimes(1)
    expect(removeTab).toHaveBeenCalledWith(100)
  })
  test("lets a completed page hydrate its session before trusting an initial login route", async () => {
    vi.useFakeTimers()
    getTab.mockResolvedValueOnce({ id: 100, url: new URL("/login", homeUrl).href, status: "complete", active: false })
    executeScript.mockResolvedValueOnce([{ result: { state: "login_required" } }])
      .mockResolvedValueOnce([{ result: { state: "logged_in", name: "加载后的本人" } }])
    const result = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(301)
    expect(await result).toMatchObject({ state: "logged_in", name: "加载后的本人" })
    expect(executeScript).toHaveBeenCalledTimes(2)
    expect(removeTab).toHaveBeenCalledTimes(1)
  })
  test("recognizes a settled visitor login form and removes only its temporary page", async () => {
    vi.useFakeTimers()
    executeScript.mockResolvedValue([{ result: { state: "login_required" } }])
    const result = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(901)
    expect(await result).toMatchObject({ state: "login_required" })
    expect(removeTab).toHaveBeenCalledTimes(1)
    expect(removeTab).toHaveBeenCalledWith(100)
  })
  test("bounds a shell that never hydrates and leaves its session unknown", async () => {
    vi.useFakeTimers()
    executeScript.mockResolvedValue([{ result: { state: "unknown" } }])
    const result = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(8_001)
    expect(await result).toMatchObject({ state: "unknown" })
    expect(removeTab).toHaveBeenCalledTimes(1)
    expect(removeTab).toHaveBeenCalledWith(100)
    expect(createTab).toHaveBeenCalledTimes(1)
  })
  test("bounds a stalled script and cleans up without turning a failure into logout", async () => {
    vi.useFakeTimers()
    executeScript.mockImplementation(() => new Promise(() => {}))
    const result = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(2_001)
    expect(await result).toMatchObject({ state: "unknown" })
    expect(removeTab).toHaveBeenCalledTimes(1)
    expect(removeTab).toHaveBeenCalledWith(100)
  })
  test("cleans up after script errors and tolerates an already closed temporary page", async () => {
    executeScript.mockRejectedValueOnce(new Error("Script unavailable"))
    expect(await probeAccount(platformId)).toMatchObject({ state: "unknown" })
    expect(removeTab).toHaveBeenCalledTimes(1)
    expect(removeTab).toHaveBeenCalledWith(100)
    removeTab.mockClear()
    getTab.mockRejectedValue(new Error("No tab with id"))
    expect(await probeAccount(platformId)).toMatchObject({ state: "unknown" })
    expect(removeTab).not.toHaveBeenCalled()
  })
  test("does not read or close a temporary page redirected to another origin", async () => {
    const otherOrigin = platformId === "xiaohongshu" ? "https://www.xiaohongshu.com/explore" : "https://okjike.com/"
    getTab.mockResolvedValue({ id: 100, url: otherOrigin, status: "complete", active: false })
    expect(await probeAccount(platformId)).toMatchObject({ state: "unknown" })
    expect(executeScript).not.toHaveBeenCalled()
    expect(removeTab).not.toHaveBeenCalled()
    expect(fetch).not.toHaveBeenCalled()
  })
  test.each([
    { url: homeUrl, active: true },
    { url: "https://example.com/", active: false },
    { url: homeUrl, pendingUrl: "https://example.com/", active: false }
  ])("keeps a temporary page taken over by the user: %j", async takeover => {
    getTab.mockResolvedValueOnce({ id: 100, url: homeUrl, status: "complete", active: false })
      .mockResolvedValue({ id: 100, status: "complete", ...takeover })
    executeScript.mockResolvedValue([{ result: { state: "logged_in" } }])
    expect(await probeAccount(platformId)).toMatchObject({ state: "logged_in" })
    expect(removeTab).not.toHaveBeenCalled()
  })
  test("keeps a page activated during the probe even if the user later switches tabs", async () => {
    vi.useFakeTimers()
    getTab.mockResolvedValueOnce({ id: 100, url: homeUrl, status: "complete", active: true })
    executeScript.mockResolvedValueOnce([{ result: { state: "unknown" } }])
      .mockResolvedValueOnce([{ result: { state: "logged_in" } }])
    const result = probeAccount(platformId)
    await vi.advanceTimersByTimeAsync(301)
    expect(await result).toMatchObject({ state: "logged_in" })
    expect(removeTab).not.toHaveBeenCalled()
  })
})

describe("X session origin boundaries", () => {
  beforeEach(() => {
    createTab.mockResolvedValue({ id: 100, url: "https://x.com/home", status: "loading", active: false })
  })
  test("accepts a normal redirect to Twitter's own session and removes only the temporary page", async () => {
    getTab.mockResolvedValue({ id: 100, url: "https://twitter.com/home", status: "complete", active: false })
    executeScript.mockResolvedValue([{ result: { state: "logged_in", name: "same_session" } }])
    expect(await probeAccount("x-post")).toMatchObject({ state: "logged_in", name: "same_session" })
    expect(executeScript).toHaveBeenCalledWith(expect.objectContaining({ args: ["x-article"] }))
    expect(removeTab).toHaveBeenCalledWith(100)
  })
  test.each([
    "https://example.com/",
    "https://x.com.example.com/home",
    "http://x.com/home",
    "https://x.com:444/home",
    "https://www.twitter.com/home"
  ])("does not inspect or close a temporary session moved outside the allowed X origins: %s", async url => {
    getTab.mockResolvedValue({ id: 100, url, status: "complete", active: false })
    expect(await probeAccount("x-post")).toMatchObject({ state: "unknown" })
    expect(executeScript).not.toHaveBeenCalled()
    expect(removeTab).not.toHaveBeenCalled()
    expect(fetch).not.toHaveBeenCalled()
  })
  test("does not inspect an existing X page that moved to another origin after the tab query", async () => {
    query.mockResolvedValue([{ id: 8, url: "https://x.com/home", status: "complete" }])
    getTab.mockResolvedValue({ id: 8, url: "https://example.com/", status: "complete", active: true })
    expect(await probeAccount("x-post")).toMatchObject({ state: "unknown" })
    expect(executeScript).not.toHaveBeenCalled()
    expect(createTab).not.toHaveBeenCalled()
    expect(removeTab).not.toHaveBeenCalled()
  })
})

describe("Weibo bootstrap formats", () => {
  test("parses nested current JSON with escaped quotes and braces in names", () => {
    const user = { idstr: "123456", screen_name: '昵称 } "测试"', avatar_large: "https://example.com/a.jpg" }
    expect(parseWeiboAccount(`<script>window.$CONFIG = ${JSON.stringify({ user, other: { deep: {} } })};window.extra=1</script>`)).toEqual({ state: "logged_in", name: user.screen_name, avatar: user.avatar_large })
  })
  test("supports legacy account assignments without evaluating scripts", () => {
    expect(parseWeiboAccount(`<script>$CONFIG['uid']='123456';$CONFIG['nick']='旧账号';throw Error('never run')</script>`)).toEqual({ state: "logged_in", name: "旧账号" })
    expect(parseWeiboAccount(`<script>window.$CONFIG={user:runCode()};</script>`)).toEqual({ state: "unknown" })
    expect(parseWeiboAccount(`<script>$CONFIG['uid']=0;</script>`)).toEqual({ state: "unknown" })
  })
})
